class Command(BaseCommand):
    help = "Seed interactive equations for the additional subjects (CS, Chemistry, ...)."

    def handle(self, *args, **options):
        created = 0
        updated = 0
        for eq in SUBJECT_EQUATIONS:
            data = {
                "title": eq["title"],
                "formula": eq["formula"],
                "author": eq["author"],
                "year": eq["year"],
                "category": eq["category"],
                "description": eq["description"],
                "stage": "live-demo",
                "hook": eq["hook"],
                "hook_action": eq["hook_action"],
                "variables_data": eq["variables"],
                "presets_data": eq["presets"],
                "lessons_data": eq["lessons"],
                "glossary_data": eq.get("glossary", []),
            }
            _, was_created = Equation.objects.update_or_create(
                sort_order=eq["sort_order"],
                defaults=data,
            )
            created += 1 if was_created else 0
            updated += 0 if was_created else 1

        self.stdout.write(self.style.SUCCESS(
            f"Seeded {len(SUBJECT_EQUATIONS)} subject equations ({created} created, {updated} updated)"
        ))
