"""Seed interactive equations for the additional subjects beyond the core 17.

Each equation carries a full teaching payload (hook, variables, presets, guided
lesson steps, glossary). The frontend renders these through the data-driven
ConfigurableEquationScene, so no bespoke D3 scene is required.

Run with:  python manage.py seed_subjects
The core 17 are seeded separately by ``seed_equations``.
"""

from django.core.management.base import BaseCommand

from courses.models import Equation


def var(name, symbol, description, *, min, max, step, default, color, unit=None, constant=False):
    return {
        "name": name,
        "symbol": symbol,
        "description": description,
        "min": min,
        "max": max,
        "step": step,
        "default": default,
        "unit": unit,
        "color": color,
        "constant": constant,
    }


def lesson(id, instruction, insight, *, hint="", unlocked=None, success_type="variable_changed",
           target=None, value=None, tolerance=None, celebration="subtle"):
    step = {
        "id": id,
        "instruction": instruction,
        "hint": hint,
        "unlocked": unlocked or [],
        "successType": success_type,
        "celebration": celebration,
        "insight": insight,
    }
    if target is not None:
        step["successTarget"] = target
    if value is not None:
        step["successValue"] = value
    if tolerance is not None:
        step["successTolerance"] = tolerance
    return step


